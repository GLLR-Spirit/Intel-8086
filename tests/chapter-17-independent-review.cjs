const fs = require("node:fs");
const assert = require("node:assert/strict");
const key = JSON.parse(fs.readFileSync("docs/question-semantic-key-8086.json", "utf8"));
const review = JSON.parse(fs.readFileSync("docs/question-independent-review/chapter-17.json", "utf8"));
const chapterIds = key.questions.filter(q => q.chapter === 17).map(q => q.id).sort();
const reviewedIds = review.records.map(r => r.id).sort();
assert.equal(chapterIds.length, 19, "Chapter 17 must contain 19 assessment questions");
assert.deepEqual(reviewedIds, chapterIds, "Chapter 17 review must cover every question exactly once");
assert.equal(new Set(reviewedIds).size, 19, "Chapter 17 review IDs must be unique");
assert.equal(review.summary.questionsReviewed, 19);
assert.equal(review.summary.passed, 13);
assert.equal(review.summary.corrected, 6);
assert.equal(review.summary.needsRevision, 0);
assert.equal(review.summary.blocked, 0);
assert.equal(review.summary.officialCertificationCountBefore, 384);
assert.equal(review.summary.officialCertificationCountAfter, 384);
assert.equal(review.summary.remainingOfficialCertification, 300);
const correctedIds = new Set(["C17-L1-Q1","C17-F-Q3","C17-F-Q4","C17-F-Q7","C17-F-Q8","C17-F-Q10"]);
for (const id of correctedIds) assert.ok(review.records.some(r => r.id === id && r.result === "corrected"), "Corrected question must be recorded: " + id);
assert.ok(review.openFindings.some(f => f.id === "final-assessment-blueprint"), "The unresolved final-assessment blueprint must remain visible");
console.log("Chapter 17 independent review: 19/19 inspected; 13 passed; 6 corrections aligned; final-assessment blueprint remains open; official certification remains 384/684.");
