const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");

const html = fs.readFileSync("index.html", "utf8");
const match = html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(match, "Inline application script must exist");

const elements = new Map();
function element(id) {
  if (!elements.has(id)) {
    elements.set(id, {
      id, value: "", textContent: "", innerHTML: "", className: "",
      dataset: {}, onclick: null, oninput: null, onchange: null
    });
  }
  return elements.get(id);
}
const context = {
  document: { getElementById: element, querySelectorAll: () => [] },
  localStorage: { getItem: () => null, setItem: () => {}, removeItem: () => {} },
  console
};
vm.createContext(context);
const instrumented = match[1].replace(/\\n\\}\\)\\(\\);\\s*$/, `
globalThis.__8086TestApi = {
  assemble: function (source) { return assembleProgram(source); },
  disassemble: function (bytes) { return disassembleBytes(bytes); },
  run: function (source) {
    prepare(source);
    while (!halted && pc < ops.length) tick();
    return JSON.parse(JSON.stringify(cpu));
  }
};
})();
`);
assert.notEqual(instrumented, match[1], "Test API injection point must exist");
vm.runInContext(instrumented, context, { timeout: 5000 });
const api = context.__8086TestApi;
assert.ok(api, "Internal test API must be exposed");

let passed = 0;
function test(name, fn) {
  try {
    fn();
    passed++;
    console.log("PASS " + name);
  } catch (error) {
    console.error("FAIL " + name + ": " + error.message);
    process.exitCode = 1;
  }
}
function bytesOf(source) {
  return Array.from(api.assemble(source).bytes);
}
function disassemble(bytes) {
  return api.disassemble(bytes);
}
function execute(source) {
  return api.run(source);
}
function hex(bytes) {
  return bytes.map((b) => b.toString(16).padStart(2, "0").toUpperCase()).join(" ");
}

// Independent assembler byte vectors: expected bytes are literals, not generated by the decoder.
const assemblerVectors = [
  ["MOV register immediate", "MOV AX, 1234h", [0xB8, 0x34, 0x12]],
  ["MOV segment register", "MOV DS, AX", [0x8E, 0xD8]],
  ["MOV direct memory from register", "MOV WORD PTR [2000h], BX", [0x89, 0x1E, 0x00, 0x20]],
  ["ADD register to register", "ADD AX, BX", [0x03, 0xC3]],
  ["ADD accumulator immediate", "ADD AX, 1234h", [0x05, 0x34, 0x12]],
  ["SUB register from accumulator", "SUB AX, BX", [0x2B, 0xC3]],
  ["CMP register against accumulator", "CMP AX, BX", [0x3B, 0xC3]],
  ["CMP accumulator immediate", "CMP AX, 1234h", [0x3D, 0x34, 0x12]]
];
for (const [name, source, expected] of assemblerVectors) {
  test("Assembler · " + name, () => {
    const actual = bytesOf(source);
    assert.deepEqual(actual, expected, "expected " + hex(expected) + ", got " + hex(actual));
  });
}

// ADC/SBB are deliberately asserted as unsupported until implementation is authorized.
for (const mnemonic of ["ADC", "SBB"]) {
  test("Assembler · " + mnemonic + " limitation is explicit", () => {
    assert.throws(() => bytesOf(mnemonic + " AX, BX"), /non pris en charge|instruction inconnue/i);
  });
}

// Independent decoder vectors use fixed machine bytes, not the assembler's output.
const decoderVectors = [
  ["MOV register immediate", [0xB8, 0x34, 0x12], /MOV AX,1234h/i],
  ["MOV segment register", [0x8E, 0xD8], /MOV DS,AX/i],
  ["MOV direct memory from register", [0x89, 0x1E, 0x00, 0x20], /MOV WORD PTR \[2000h\],BX/i],
  ["ADD register to register", [0x03, 0xC3], /ADD AX,BX/i],
  ["SUB register from accumulator", [0x2B, 0xC3], /SUB AX,BX/i],
  ["CMP register against accumulator", [0x3B, 0xC3], /CMP AX,BX/i]
];
for (const [name, machineBytes, expectedText] of decoderVectors) {
  test("Désassembleur · " + name, () => {
    const result = disassemble(machineBytes);
    assert.equal(result.rows.length, 1);
    assert.match(result.rows[0].instruction.replace(/\s+/g, ""), expectedText);
    assert.deepEqual(Array.from(result.rows[0].bytes), machineBytes);
  });
}
test("Désassembleur · flux MOV tronqué refusé", () => {
  assert.throws(() => disassemble([0xB8, 0x34]), /tronqué/i);
});

// Simulator tests are intentionally separate from assembler/disassembler tests.
test("Simulateur · MOV puis ADD modifie AX", () => {
  const state = execute("MOV AX, 5\nMOV BX, 3\nADD AX, BX\nHLT");
  assert.equal(state.reg.AX, 8);
});
test("Simulateur · ADD 8 bits calcule CF et ZF", () => {
  const state = execute("MOV AL, 255\nADD AL, 1\nHLT");
  assert.equal(state.reg.AX & 0xFF, 0);
  assert.equal(state.flags.CF, 1);
  assert.equal(state.flags.ZF, 1);
});
test("Simulateur · SUB calcule l'emprunt", () => {
  const state = execute("MOV AL, 0\nSUB AL, 1\nHLT");
  assert.equal(state.reg.AX & 0xFF, 0xFF);
  assert.equal(state.flags.CF, 1);
});
test("Simulateur · CMP modifie FLAGS sans modifier les opérandes", () => {
  const state = execute("MOV AX, 5\nMOV BX, 3\nCMP AX, BX\nHLT");
  assert.equal(state.reg.AX, 5);
  assert.equal(state.reg.BX, 3);
  assert.equal(state.flags.CF, 0);
  assert.equal(state.flags.ZF, 0);
});
test("Simulateur · CMP égal active ZF", () => {
  const state = execute("MOV AX, 7\nCMP AX, 7\nHLT");
  assert.equal(state.reg.AX, 7);
  assert.equal(state.flags.ZF, 1);
});
for (const mnemonic of ["ADC", "SBB"]) {
  test("Simulateur · " + mnemonic + " limitation détectée", () => {
    assert.throws(() => execute(mnemonic + " AX, BX"), /instruction inconnue|inconnue/i);
  });
}

console.log("\nRésultat vecteurs indépendants : " + passed + " tests réussis.");
if (process.exitCode) process.exit(process.exitCode);
