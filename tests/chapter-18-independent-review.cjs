"use strict";
const fs = require("node:fs");
const assert = require("node:assert/strict");
const key = JSON.parse(fs.readFileSync("docs/question-semantic-key-8086.json", "utf8"));
const batch = JSON.parse(fs.readFileSync("docs/question-oracle-batches/chapter-18.json", "utf8"));
const review = JSON.parse(fs.readFileSync("docs/question-independent-review/chapter-18.json", "utf8"));
const expectedIds = key.questions.filter(q => q.chapter === 18).map(q => q.id).sort();
const reviewedIds = review.records.map(r => r.id).sort();
assert.equal(expectedIds.length, 19, "Chapter 18 must contain 19 questions");
assert.deepEqual(reviewedIds, expectedIds, "Chapter 18 review must cover every question exactly once");
assert.equal(new Set(reviewedIds).size, 19, "Chapter 18 review IDs must be unique");
assert.equal(review.summary.questionsReviewed, 19);
assert.equal(review.summary.passed, 15);
assert.equal(review.summary.corrected, 4);
assert.equal(review.summary.needsRevision, 0);
assert.equal(review.summary.blocked, 0);
assert.deepEqual(review.openFindings, [], "Chapter 18 review must have no open item-level findings");
const finalQuestions = key.questions.filter(q => q.chapter === 18 && q.kind === "final");
const categories = ["Définition","Syntaxe","Calcul / prédiction","Analyse de programme","Raisonnement / débogage"];
for (const category of categories) assert.equal(finalQuestions.filter(q => q.category === category).length, 2,
  "Chapter 18 final assessment must contain exactly two " + category + " items");
const f8 = batch.oracles.find(q => q.id === "C18-F-Q8");
assert.ok(f8, "Chapter 18 F8 oracle must exist");
assert.equal(f8.correctAnswer, key.questions.find(q => q.id === "C18-F-Q8").correctAnswer);
assert.deepEqual(f8.expected.physicalAddresses, [65552,65552]);
assert.equal(f8.expected.samePhysical, true);
const corrected = new Set(["C18-L1-Q2","C18-L1-Q3","C18-F-Q2","C18-F-Q8"]);
for (const id of corrected) assert.ok(review.records.some(r => r.id === id && r.result === "corrected"), "Correction must be recorded: " + id);
console.log("Chapter 18 independent review: 19/19 inspected; 15 passed; 4 corrected; final-assessment blueprint balanced; official ledger unchanged at 384/684.");
