const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const html=fs.readFileSync("index.html","utf8"),match=html.match(/<script>([\s\S]*?)<\/script>/);assert.ok(match);
const elements=new Map();function element(id){if(!elements.has(id))elements.set(id,{id,value:"",textContent:"",innerHTML:"",className:"",dataset:{},onclick:null,oninput:null,onchange:null});return elements.get(id);}
const context={document:{getElementById:element,querySelectorAll:()=>[]},localStorage:{getItem:()=>null,setItem:()=>{},removeItem:()=>{}},console};
vm.createContext(context);
const injection="\nglobalThis.api={assemble:s=>assembleProgram(s),disassemble:b=>disassembleBytes(b),execute:s=>executeAll(s),binary:(b,c,i,s)=>executeBinary(b,c,i,s)};\n})();\n";
const instrumented=match[1].replace(/\n\}\)\(\);\s*$/,injection);assert.notEqual(instrumented,match[1]);
vm.runInContext(instrumented,context,{timeout:30000});
const api=context.api;
const direct="JMP FAR 1234h:0003h\nMOV AX, 1\nMOV AX, 2\nHLT";
const encoded=Array.from(api.assemble(direct).bytes);
assert.deepEqual(encoded.slice(0,5),[0xEA,0x03,0x00,0x34,0x12],"EA far JMP offset then segment little-endian");
assert.equal(api.disassemble(encoded).rows[0].instruction,"JMP FAR 1234h:0003h");
const sourceState=api.execute(direct);
assert.equal(sourceState.error,undefined,"source far JMP");
assert.equal(sourceState.reg.CS,0x1234);
assert.equal(sourceState.reg.IP,4,"HLT advances to the byte after the target instruction in the source model.");
assert.equal(sourceState.reg.AX,0,"both MOV instructions skipped by far JMP");
assert.equal(sourceState.reg.SP,0xFFFE,"JMP does not push a return frame");
const main=Array.from(api.assemble("JMP FAR 2000h:0100h\nHLT").bytes);
const target=0x2000*16+0x0100;
const initial={mem:{[target]:0xB8,[target+1]:0x34,[target+2]:0x12,[target+3]:0xF4},reg:{SP:0xFFFE},flags:{CF:1,PF:1,AF:1,ZF:1,SF:1,TF:1,IF:1,DF:1,OF:1}};
const binaryState=api.binary(main,0,0,initial);
assert.equal(binaryState.error,undefined,"binary far JMP");
assert.equal(binaryState.reg.CS,0x2000);
assert.equal(binaryState.reg.IP,0x0104);
assert.equal(binaryState.reg.AX,0x1234);
assert.equal(binaryState.reg.SP,0xFFFE,"binary far JMP leaves stack unchanged");
for(const flag of ["CF","PF","AF","ZF","SF","TF","IF","DF","OF"])assert.equal(binaryState.flags[flag],1,flag+" preserved by JMP");
console.log("8086 JMP FAR direct: EA encoding, source/binary CS:IP, no stack frame and FLAGS preservation PASS.");
