const fs = require("node:fs");
const assert = require("node:assert/strict");
const key = JSON.parse(fs.readFileSync("docs/question-semantic-key-8086.json", "utf8"));
const review = JSON.parse(fs.readFileSync("docs/question-independent-review/chapter-16.json", "utf8"));
const chapterIds = key.questions.filter(q => q.chapter === 16).map(q => q.id).sort();
const reviewedIds = review.records.map(r => r.id).sort();
assert.equal(chapterIds.length, 19, "Chapter 16 must contain 19 assessment questions");
assert.deepEqual(reviewedIds, chapterIds, "Chapter 16 review must cover every question exactly once");
assert.equal(new Set(reviewedIds).size, 19, "Chapter 16 review IDs must be unique");
assert.equal(review.summary.questionsReviewed, 19);
assert.equal(review.summary.passed, 15);
assert.equal(review.summary.needsRevision, 0);
assert.equal(review.summary.corrected, 4, "All four repetition corrections must be recorded after runtime/key/oracle changes");
assert.equal(review.summary.blocked, 0);
assert.equal(review.summary.officialCertificationCountBefore, 384);
assert.equal(review.summary.officialCertificationCountAfter, 384);
assert.equal(review.summary.remainingOfficialCertification, 300);
const correctedIds = new Set(["C16-L1-Q1","C16-L2-Q1","C16-L3-Q1","C16-F-Q8"]);
for (const id of correctedIds) assert.ok(review.records.some(r => r.id === id && r.result === "corrected"), "Corrected question must be recorded: " + id);
console.log("Chapter 16 independent review: 19/19 inspected; 15 passed; 4 repetition corrections aligned across runtime, key and oracle; official certification remains 384/684.");
